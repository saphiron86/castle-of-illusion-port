std::string hex6(uint32_t a)
{
    char buf[16];
    std::snprintf(buf, sizeof(buf), "%06X", a & 0xFFFFFF);
    return buf;
}

std::string hexv(uint32_t v)
{
    char buf[16];
    std::snprintf(buf, sizeof(buf), "0x%Xu", v);
    return buf;
}

class CEmitter {
public:
    explicit CEmitter(const Program& program) : program(program) {}

    // The resumable copy for --readable: its functions are coi_rs_XXXXXX (not static), and its
    // calls go to the readable functions (`callee`), as new calls do.
    void resumable(std::function<std::string(uint32_t)> readable)
    {
        prefix = "coi_rs_";
        storage = "";
        callee = std::move(readable);
    }

    // Only these functions, with no header (a setting's variant, docs/decompile.md).
    std::string emit_resumable_part(const std::set<uint32_t>& entries)
    {
        std::ostringstream out;
        for (uint32_t entry : entries)
            emit_function(out, program.functions().at(entry));
        return out.str();
    }

    // Variants (docs/decompile.md): this copy's functions are coi_rs_XXXXXX<suffix>; a base
    // function hands its call to each of its settings' versions while that setting's bit is set;
    // the resume table also takes instructions only a variant has (to the base function); the
    // image family's hashes (the base, then each setting's image) go with the tables.
    std::string suffix;
    std::map<uint32_t, std::vector<std::pair<uint32_t, std::string>>> dispatch;
    std::map<uint32_t, uint32_t> extra_resume;
    std::vector<uint64_t> family;
    // A variant's resume points that it doesn't hold itself (the resume table gives the base
    // function, but with the setting on, the instruction is another function's): per function,
    // the address and the function to hand it to.
    std::map<uint32_t, std::vector<std::pair<uint32_t, std::string>>> redirect;
    // Hand-written patches (config/patches.txt), and the settings this copy's functions are a
    // variant of (`own_bits`: those settings' patches aren't put in them).
    const std::map<uint32_t, Patch>* patches = nullptr;
    uint32_t own_bits = 0;
    // The resumable copy's head when there are patches: their names (readable_rt.h, the settings'
    // bits, the fixed addresses they use).
    std::string patch_head;

    std::string emit_resumable()
    {
        std::ostringstream out;
        out << "/* Generated by coi_recomp --readable from the player's ROM: game code, not for the repository.\n"
               " * The resumable copy of every function: each instruction a label, so a call stopped partway\n"
               " * (at a scanline's end) can carry on from any instruction. */\n"
               "#include \"native_rt.h\"\n"
               "extern uint32_t coi_native_settings;   /* the settings' bits (main.cpp) */\n\n";
        out << patch_head;
        out << "CoiNativeFn coi_native_lookup(uint32_t address);\n\n";
        for (const auto& [entry, f] : program.functions())
            emit_function(out, f);
        return out.str();
    }

    std::string emit()
    {
        const auto& functions = program.functions();
        std::ostringstream out;
        out << "/* Generated by coi_recomp from the player's ROM: game code, not for the repository. */\n"
               "#include \"native_rt.h\"\n"
               "extern uint32_t coi_native_settings;   /* the settings' bits (main.cpp) */\n\n";
        for (const auto& [entry, f] : functions)
            out << "static uint32_t coi_fn_" << hex6(entry) << "(CoiCpu* c, uint32_t at);\n";
        out << "\n";
        out << run_and_tables(false);
        return out.str();
    }

    // coi_native_run, then (`tables_only`: without the functions) the lookup and resume tables,
    // the ROM's size and hash and coi_native_c, for functions named by `callee`.
    std::string run_and_tables(bool tables_only)
    {
        const auto& functions = program.functions();
        std::ostringstream out;
        out << "CoiNativeFn coi_native_lookup(uint32_t address);\n\n";
        out << "uint32_t coi_native_run(CoiCpu* c, CoiNativeFn fn, uint32_t at)\n{\n"
               "    uint32_t r = fn(c, at);\n"
               "    while (c->jump && !c->fail) {\n"
               "        c->jump = 0;\n"
               "        if (!(fn = coi_native_lookup(r))) { c->fail = r; return 0; }\n"
               "        r = fn(c, 0);\n"
               "    }\n"
               "    return r;\n}\n\n";
        if (!tables_only)
            for (const auto& [entry, f] : functions)
                emit_function(out, f);
        out << "CoiNativeFn coi_native_lookup(uint32_t address)\n{\n    switch (address) {\n";
        for (const auto& [entry, f] : functions)
            out << "    case " << hexv(entry) << ": return " << callee(entry) << ";\n";
        out << "    }\n    return 0;\n}\n\n";
        // Each instruction once, with the first function that holds it.
        std::map<uint32_t, uint32_t> resume;
        for (const auto& [entry, f] : functions)
            for (const auto& [a, in] : f.insns)
                resume.emplace(a, entry);
        for (const auto& [a, entry] : extra_resume)
            resume.emplace(a, entry);
        out << "const CoiResume coi_native_resume[] = {\n";
        for (const auto& [a, entry] : resume)
            out << "    {" << hexv(a) << ", " << callee(entry) << "},\n";
        out << "    {0, 0}};\nconst int coi_native_resume_count = " << resume.size() << ";\n\n";
        const auto& rom = program.rom().bytes;
        out << "const uint32_t coi_native_rom_size = " << rom.size() << "u;\n";
        out << "const uint64_t coi_native_rom_hash = " << coi_native_hash(rom.data(), uint32_t(rom.size())) << "ull;\n\n";
        out << "const uint32_t coi_native_entries[] = {";
        for (uint32_t e : program.entries())
            out << hexv(e) << ", ";
        out << "0};\nconst int coi_native_entry_count = " << program.entries().size() << ";\n\n";
        out << "const uint64_t coi_native_family[] = {";
        for (uint64_t h : family)
            out << h << "ull, ";
        out << "0};\nconst int coi_native_family_count = " << family.size() << ";\n\n";
        out << "const CoiNativeCode coi_native_c = {coi_native_lookup, coi_native_run, coi_native_resume, "
            << resume.size() << ", coi_native_entries, " << program.entries().size() << ", " << rom.size() << "u, "
            << coi_native_hash(rom.data(), uint32_t(rom.size())) << "ull};\n";
        return out.str();
    }

private:
    // The patch in place of the instruction at `a`, unless the function is (or has) a variant of
    // its setting, or the instruction isn't the one it replaces.
    const Patch* patch_at(uint32_t a, const Insn& in, uint32_t bits) const
    {
        if (!patches) return nullptr;
        auto p = patches->find(a);
        if (p == patches->end() || (bits & (1u << p->second.bit))) return nullptr;
        const auto& rom = program.rom().bytes;
        if (uint32_t(in.length) > p->second.original.size()) return nullptr;
        for (size_t q = 0; q < p->second.original.size(); q++)
            if (a + q >= rom.size() || rom[a + q] != p->second.original[q]) return nullptr;
        return &p->second;
    }

    const Program& program;
    std::ostringstream* o = nullptr;
    std::string prefix = "coi_fn_", storage = "static ";
    std::function<std::string(uint32_t)> callee = [](uint32_t a) { return "coi_fn_" + hex6(a); };

    void line(const std::string& s) { *o << "        " << s << "\n"; }
    static std::string reg(uint32_t i) { return i < 8 ? "c->d[" + std::to_string(i) + "]" : "c->a[" + std::to_string(i - 8) + "]"; }
    static std::string val(const Val& v) { return v.kind == Val::Imm ? hexv(v.n) : "t" + std::to_string(v.n); }

    void emit_function(std::ostringstream& out, const Function& f)
    {
        o = &out;
        if (auto d = dispatch.find(f.entry); d != dispatch.end())   // (the variants, declared before use)
            for (const auto& [bit, s] : d->second)
                out << storage << "uint32_t " << prefix << hex6(f.entry) << s << "(CoiCpu* c, uint32_t at);\n";
        out << storage << "uint32_t " << prefix << hex6(f.entry) << suffix << "(CoiCpu* c, uint32_t at)\n{\n";
        if (auto d = dispatch.find(f.entry); d != dispatch.end())
            for (const auto& [bit, s] : d->second)
                out << "    if (coi_native_settings & " << hexv(1u << bit) << ") return " << prefix << hex6(f.entry) << s
                    << "(c, at);\n";
        uint32_t bits = own_bits;
        if (auto d = dispatch.find(f.entry); d != dispatch.end())
            for (const auto& [bit, s] : d->second) bits |= 1u << bit;
        out << "    switch (at) {\n";
        for (const auto& [a, in] : f.insns)
            if (a != f.entry)
                out << "    case " << hexv(a) << ": goto L_" << hex6(a) << ";\n";
        for (const auto& [a, in] : f.insns)             // (inside a patch: where it can stop)
            if (const Patch* p = patch_at(a, in, bits))
                for (uint32_t s : p->steps)
                    out << "    case " << hexv(s) << ": goto P_" << hex6(s) << ";\n";
        if (auto rd = redirect.find(f.entry); rd != redirect.end())
            for (const auto& [a, to] : rd->second)
                out << "    case " << hexv(a) << ": return " << to << "(c, at);\n";
        out << "    }\n";
        out << "    goto L_" << hex6(f.entry) << ";\n";
        uint32_t expected = 0xFFFFFFFF;
        for (const auto& [a, in] : f.insns) {
            if (expected != 0xFFFFFFFF && a != expected)
                out << "    goto L_" << hex6(expected) << ";\n";
            out << "L_" << hex6(a) << ": {\n";
            IrBlock block = lower(program, in);
            const Patch* p = patch_at(a, in, bits);
            if (p && p->is_value()) {
                uint32_t t = 0;
                name_value(block, *p, t);
                out << "        uint32_t t" << t << " = " << p->value_name << ";\n";
                emit_block(block);
            } else if (!p) {
                emit_block(block);
            } else {
                // Up to the instruction's stop check, then the setting's C in its place.
                size_t k = 0;
                while (k < block.code.size() && !(block.code[k].op == Ir::Limit && block.code[k].k == a)) k++;
                if (k == block.code.size())
                    throw std::runtime_error("the patch at $" + hex6(a) + ": no stop check to put it after");
                IrBlock before = block, after = block;
                before.code.assign(block.code.begin(), block.code.begin() + std::ptrdiff_t(k + 1));
                after.code.assign(block.code.begin() + std::ptrdiff_t(k + 1), block.code.end());
                emit_block(before);
                out << "        if (SETTING(" << p->setting << ")) {\n";
                for (std::string l : p->rs_lines) {
                    // (STEP: the next instruction's start, as the resumable copy has one)
                    for (size_t q = l.find("STEP("); q != std::string::npos; q = l.find("STEP(")) {
                        const size_t e = l.find(';', q);
                        const uint32_t s = uint32_t(std::stoul(l.substr(q + 5), nullptr, 16));
                        l = l.substr(0, q) + "P_" + hex6(s) + ": RT_TRACE(c, " + hexv(s) + "); RT_LIMIT(c, " + hexv(s) + ");"
                            + l.substr(e + 1);
                    }
                    out << (l.empty() ? "" : "            " + l) << "\n";
                }
                if (!p->leaves) {
                    const uint32_t next = a + uint32_t(p->original.size());
                    if (!f.insns.count(next))
                        throw std::runtime_error("the patch at $" + hex6(a) + " goes on to $" + hex6(next)
                                                 + ", which isn't in the function");
                    out << "            goto L_" << hex6(next) << ";\n";
                }
                out << "        }\n";
                emit_block(after);
            }
            out << "    }\n";
            expected = ends_block(in) ? 0xFFFFFFFF : a + uint32_t(in.length);
        }
        if (expected != 0xFFFFFFFF)
            out << "    goto L_" << hex6(expected) << ";\n";
        out << "}\n\n";
    }

    // One instruction's IR as C: each temporary a variable, each local label L_<insn>_<n>.
    void emit_block(const IrBlock& block)
    {
        const std::string local = "L_" + hex6(block.address) + "_";
        for (const IrInst& i : block.code) {
            const std::string a = val(i.a), b = val(i.b), S = std::to_string(i.size), k = std::to_string(i.k);
            const std::string d = "uint32_t t" + std::to_string(i.dst) + " = ";
            switch (i.op) {
            case Ir::Mov: line(d + a + ";"); break;
            case Ir::GetReg: line(d + reg(i.k) + ";"); break;
            case Ir::Add: line(d + a + " + " + b + ";"); break;
            case Ir::Sub: line(d + a + " - " + b + ";"); break;
            case Ir::And: line(d + a + " & " + b + ";"); break;
            case Ir::Or: line(d + a + " | " + b + ";"); break;
            case Ir::Xor: line(d + a + " ^ " + b + ";"); break;
            case Ir::Shl: line(d + a + " << " + b + ";"); break;
            case Ir::Shr: line(d + a + " >> " + b + ";"); break;
            case Ir::Eq: line(d + "(uint32_t)(" + a + " == " + b + ");"); break;
            case Ir::Ne: line(d + "(uint32_t)(" + a + " != " + b + ");"); break;
            case Ir::Ltu: line(d + "(uint32_t)(" + a + " < " + b + ");"); break;
            case Ir::MulU16: line(d + "(" + a + " & 0xFFFFu) * (" + b + " & 0xFFFFu);"); break;
            case Ir::MulS16: line(d + "(uint32_t)((int32_t)(int16_t)" + a + " * (int32_t)(int16_t)" + b + ");"); break;
            case Ir::Sext: line(d + "rt_sext(" + S + ", " + a + ");"); break;
            case Ir::Read: line(d + "rt_read(" + S + ", " + a + ");"); break;
            case Ir::GetSrHigh: line(d + "(uint32_t)c->sr_high;"); break;
            case Ir::GetUsp: line(d + "c->usp;"); break;
            case Ir::AddF: line(d + "rt_add(c, " + S + ", " + a + ", " + b + ");"); break;
            case Ir::SubF: line(d + "rt_sub(c, " + S + ", " + a + ", " + b + ");"); break;
            case Ir::AddxF: line(d + "rt_addx(c, " + S + ", " + a + ", " + b + ");"); break;
            case Ir::SubxF: line(d + "rt_subx(c, " + S + ", " + a + ", " + b + ");"); break;
            case Ir::LogicF: line(d + "rt_logic(c, " + S + ", " + a + ");"); break;
            case Ir::ShiftF: line(d + "rt_shift(c, " + k + ", " + S + ", " + a + ", (int)" + b + ");"); break;
            case Ir::Cond: line(d + "(uint32_t)rt_cond(c, " + k + ");"); break;
            case Ir::GetCcr: line(d + "rt_ccr(c);"); break;
            case Ir::MuluCycles: line(d + "(uint32_t)rt_mulu_cycles(" + a + ");"); break;
            case Ir::MulsCycles: line(d + "(uint32_t)rt_muls_cycles(" + a + ");"); break;
            case Ir::Divu: line(d + "(uint32_t)rt_divu(c, " + k + ", " + a + ");"); break;
            case Ir::Divs: line(d + "(uint32_t)rt_divs(c, " + k + ", " + a + ");"); break;
            case Ir::Pop32: line(d + "rt_pop32(c);"); break;
            case Ir::IrqLevel: line(d + "(uint32_t)coi_native_irq_level();"); break;
            case Ir::Interrupt: line(d + "coi_native_interrupt(c, " + a + ");"); break;
            case Ir::Exception: line(d + "coi_native_exception(c, " + hexv(i.k) + ", " + a + ", " + hexv(i.k2) + ");"); break;
            case Ir::StopCpu: line(d + "coi_native_stop(c, " + a + ", " + b + ");"); break;
            case Ir::SetReg: line(reg(i.k) + " = " + a + ";"); break;
            case Ir::SetRegPart: line("rt_setd(c, " + k + ", " + S + ", " + a + ");"); break;
            case Ir::Write: line("rt_write(" + S + ", " + a + ", " + b + ");"); break;
            case Ir::CmpF: line("rt_cmp(c, " + S + ", " + a + ", " + b + ");"); break;
            case Ir::SetCcr: line("rt_set_ccr(c, " + a + ");"); break;
            case Ir::SetSrHigh: line("c->sr_high = (uint16_t)" + a + ";"); break;
            case Ir::SetUsp: line("c->usp = " + a + ";"); break;
            case Ir::SetZ: line("c->z = (" + a + " & " + b + ") == 0;"); break;
            case Ir::Push32: line("rt_push32(c, " + a + ");"); break;
            case Ir::Spin: line("rt_spin(c, " + std::to_string(i.k) + ");"); break;
            case Ir::SetSr: line("rt_set_sr(c, " + a + ");"); break;
            case Ir::Cycles: line("RT_CYCLES(c, " + hexv(i.k) + ");"); break;
            case Ir::AddCycles: line("c->cycles += (int32_t)" + a + ";"); break;
            case Ir::Idle: line("RT_IDLE(c, " + a + ", " + b + ", " + S + ", " + hexv(i.k) + ", " + hexv(i.k2) + ");"); break;
            case Ir::Label: line(local + k + ": ;"); break;
            case Ir::Br: line("goto " + local + k + ";"); break;
            case Ir::BrIf: line("if (" + a + ") goto " + local + k + ";"); break;
            case Ir::BrIfNot: line("if (!" + a + ") goto " + local + k + ";"); break;
            case Ir::Goto: line("goto L_" + hex6(i.k) + ";"); break;
            case Ir::GotoIf: line("if (" + a + ") goto L_" + hex6(i.k) + ";"); break;
            case Ir::Trace: line("RT_TRACE(c, " + hexv(i.k) + ");"); break;
            case Ir::Limit: line("RT_LIMIT(c, " + hexv(i.k) + ");"); break;
            case Ir::Stop: line("RT_STOP(c, " + hexv(i.k) + ", " + hexv(i.k2) + ");"); break;
            case Ir::SetMissing: line("c->missing = " + hexv(i.k) + ";"); break;
            case Ir::Return: line("return " + a + ";"); break;
            case Ir::JumpOut: line("c->jump = 1; return " + hexv(i.k) + ";"); break;
            case Ir::JumpDyn: line("c->jump = 1; return " + a + ";"); break;
            case Ir::Call:
                line("{ const uint32_t r = coi_native_run(c, " + callee(i.k) + ", 0); if (c->fail) return 0; if (r != "
                     + hexv(i.k2) + ") { c->fail = r; return 0; } }");
                break;
            }
        }
    }
};

// Names for the readable C: config/labels.txt's code labels (beside CONFIG), sub_XXXXXX otherwise.
// The comment after a config line's fields (after '#' in labels.txt; the rest of the line in
// ram.txt and hardware.txt), trimmed.
std::string note_of(const std::string& line, size_t fields)
{
    std::string rest;
    const size_t hash = line.find('#');
    if (fields == 0) {
        if (hash != std::string::npos) rest = line.substr(hash + 1);
    } else {
        std::istringstream s(line.substr(0, hash));
        std::string skip;
        for (size_t i = 0; i < fields && s >> skip; i++) {}
        std::getline(s, rest);
    }
    const size_t a = rest.find_first_not_of(" \t"), b = rest.find_last_not_of(" \t\r");
    rest = a == std::string::npos ? "" : rest.substr(a, b - a + 1);
    for (size_t p = rest.find("*/"); p != std::string::npos; p = rest.find("*/")) rest[p + 1] = ' ';
    return rest;
}

std::map<uint32_t, std::string> g_label_notes;

// Every label's address by name, code and data (labels.txt beside CONFIG).
std::map<std::string, uint32_t> label_addresses(const std::string& config)
{
    std::map<std::string, uint32_t> out;
    const size_t slash = config.find_last_of("/\\");
    std::ifstream f((slash == std::string::npos ? "" : config.substr(0, slash + 1)) + "labels.txt");
    std::string line;
    while (std::getline(f, line)) {
        std::istringstream s(line);
        std::string a, name;
        if ((s >> a >> name) && !a.empty() && a[0] != '#' && std::isxdigit((unsigned char)a[0]))
            out.emplace(name, uint32_t(std::stoul(a, nullptr, 16)));
    }
    return out;
}

// Names for the objects' code (readable C): each object ID's code, from the tables RunObject
// reads, as ObjXX (XX its ID), and the routines its routine table lists (a lea of the table into
// a1, then a jump to RunRoutine or RunRoutineRel) as ObjXX_N (N the ObjRoutine that selects it).
// Only where labels.txt has no name; code two objects share is named after the first.
void object_names(const Program& program, const std::map<std::string, uint32_t>& at, std::map<uint32_t, std::string>& names,
                  std::map<uint32_t, std::string>& notes, const std::map<uint32_t, std::pair<std::string, std::string>>& kinds,
                  std::map<uint32_t, uint32_t>& owner)
{
    const auto need = {"ObjectCodeLow", "ObjectCodeHigh", "RunRoutine", "RunRoutineRel"};
    for (const char* n : need)
        if (!at.count(n)) return;
    const Rom& rom = program.rom();
    const auto& fns = program.functions();
    const uint32_t low = at.at("ObjectCodeLow"), high = at.at("ObjectCodeHigh");
    const uint32_t run = at.at("RunRoutine"), run_rel = at.at("RunRoutineRel");
    std::map<uint32_t, std::vector<uint32_t>> ids;      // code -> the IDs that run it
    for (uint32_t id = 0; low + 2 * id < high; id++)
        if (fns.count(rom.word(low + 2 * id))) ids[rom.word(low + 2 * id)].push_back(id);
    for (uint32_t id = (high - low) / 2; id < 0x100; id++) {
        const uint32_t a = rom.lng(high + 4 * (id - (high - low) / 2));
        if (!fns.count(a)) break;
        ids[a].push_back(id);
    }
    auto hex2 = [](uint32_t v) { char b[8]; std::snprintf(b, sizeof b, "%02X", v); return std::string(b); };
    for (auto& [code, list] : ids) {
        // (code several IDs share: named after the first with a name in object_ids.txt)
        std::stable_partition(list.begin(), list.end(), [&](uint32_t id) { return kinds.count(id) != 0; });
        auto kind = kinds.find(list[0]);
        const std::string obj = "Obj" + (kind != kinds.end() ? kind->second.first : hex2(list[0]));
        const std::string what = kind != kinds.end() && !kind->second.second.empty() ? ", " + kind->second.second : "";
        std::string also;
        for (size_t k = 1; k < list.size(); k++) also += (k > 1 ? ", $" : " (also $") + hex2(list[k]);
        if (!also.empty()) also += ")";
        owner.emplace(code, list[0]);
        if (!names.count(code)) {
            names[code] = obj;
            if (!notes.count(code)) notes[code] = "object $" + hex2(list[0]) + what + also + ": its code, run each frame by RunObject";
        }
        // Its code may be only a jmp to the rest of it, or one instruction and the jmp (the module
        // at $07A000's objects: ObjXXMain).
        std::vector<uint32_t> parts = {code};
        const auto& insns = fns.at(code).insns;
        const uint32_t last = insns.empty() ? code : insns.rbegin()->first;
        if (insns.size() <= 2 && rom.word(last) == 0x4EF9 && fns.count(rom.lng(last + 2)) && rom.lng(last + 2) != code) {
            const uint32_t rest = rom.lng(last + 2);
            parts.push_back(rest);
            owner.emplace(rest, list[0]);
            if (!names.count(rest)) {
                names[rest] = obj + "Main";
                if (!notes.count(rest)) notes[rest] = "object $" + hex2(list[0]) + also + ": the rest of its code (its code jumps here)";
            }
        }
        // Its routine tables: lea (d16,PC),a1 then a branch, jump or call to a dispatcher.
        for (uint32_t part : parts)
        for (const auto& [x, in] : fns.at(part).insns) {
            (void)in;
            if (rom.word(x) != 0x43FA) continue;
            const uint32_t table = x + 2 + uint32_t(int32_t(int16_t(rom.word(x + 2))));
            const uint32_t y = x + 4, op = rom.word(y);
            uint32_t to = 0;
            // (bra or bsr, jmp or jsr: absolute or PC-relative)
            if (op == 0x6000 || op == 0x6100) to = y + 2 + uint32_t(int32_t(int16_t(rom.word(y + 2))));
            else if (((op >> 8) == 0x60 || (op >> 8) == 0x61) && (op & 0xFF)) to = y + 2 + uint32_t(int32_t(int8_t(op & 0xFF)));
            else if (op == 0x4EF9 || op == 0x4EB9) to = rom.lng(y + 2);
            else if (op == 0x4EF8 || op == 0x4EB8) to = uint32_t(int32_t(int16_t(rom.word(y + 2)))) & 0xFFFFFF;
            else if (op == 0x4EFA || op == 0x4EBA) to = y + 2 + uint32_t(int32_t(int16_t(rom.word(y + 2))));
            // (the module at $07A000 has its own copy of RunRoutineRel: RunRoutineRelB)
            const bool rel = to == run_rel || (at.count("RunRoutineRelB") && to == at.at("RunRoutineRelB"));
            if (to != run && !rel) continue;
            uint32_t end = 0xFFFFFFFFu;     // (the table stops before the code it lists)
            for (uint32_t n = 0; n < 64 && table + 2 * n < end; n++) {
                const uint32_t w = rom.word(table + 2 * n);
                const uint32_t target = rel ? (table + w) & 0xFFFFFF : w;
                if (!fns.count(target)) break;
                if (target > table) end = std::min(end, target);
                owner.emplace(target, list[0]);
                if (!names.count(target)) {
                    names[target] = obj + "_" + std::to_string(n);
                    if (!notes.count(target))
                        notes[target] = "object $" + hex2(list[0]) + also + ", routine " + std::to_string(n) + " (ObjRoutine = " + std::to_string(n) + ")";
                }
            }
        }
    }
    // And what only one object's functions call or jump to (its own helpers), until nothing changes.
    std::map<uint32_t, std::set<uint32_t>> callers;
    for (const auto& [entry, f] : fns)
        for (const auto& [x, in] : f.insns) {
            std::optional<uint32_t> t;
            if (in.op == Op::Jsr || in.op == Op::Jmp) t = static_target(in);
            else if (in.op == Op::Bsr || in.op == Op::Bra || in.op == Op::Bcc) t = in.target;
            if (t && fns.count(*t) && *t != entry) callers[*t].insert(entry);
        }
    for (bool changed = true; changed;) {
        changed = false;
        for (const auto& [g, from] : callers) {
            if (owner.count(g)) continue;
            uint32_t kind = 0xFFFFFFFFu;
            bool one = true;
            for (uint32_t c : from) {
                auto it = owner.find(c);
                if (it == owner.end() || (kind != 0xFFFFFFFFu && it->second != kind)) { one = false; break; }
                kind = it->second;
            }
            if (one && kind != 0xFFFFFFFFu) { owner[g] = kind; changed = true; }
        }
    }
}

std::map<uint32_t, std::string> load_labels(const std::string& config)
{
    std::map<uint32_t, std::string> names;
    std::set<std::string> taken;
    const size_t slash = config.find_last_of("/\\");
    // labels.txt, then port_labels.txt (the port's own code, from tools/boss_rush_asm.py):
    // where both name an address, the first name stands.
    for (const char* file : {"labels.txt", "port_labels.txt"}) {
        std::ifstream f((slash == std::string::npos ? "" : config.substr(0, slash + 1)) + file);
        std::string line;
        while (std::getline(f, line)) {
            std::istringstream s(line);
            std::string a, name, kind;
            if (!(s >> a >> name) || a.empty() || a[0] == '#')
                continue;
            s >> kind;
            if (kind != "code" && kind != "label")      // (a label: code inside a traced function)
                continue;
            bool ok = !name.empty() && !std::isdigit((unsigned char)name[0]);
            for (char ch : name)
                ok = ok && (std::isalnum((unsigned char)ch) || ch == '_');
            const uint32_t at = uint32_t(std::stoul(a, nullptr, 16));
            if (ok && !names.count(at) && taken.insert(name).second) {
                names[at] = name;
                const std::string note = note_of(line, 0);
                if (!note.empty()) g_label_notes[at] = note;
            }
        }
    }
    return names;
}

const std::vector<uint8_t>* g_rom_bytes = nullptr;

// config/patches.txt (docs/decompile.md, "Patches by hand"): each patch a line
// `@ <address> <setting> [note]`, then its C, indented, up to the next `@`. Comments (`#` first on
// a line) and blank lines between patches are skipped.
std::vector<Patch> load_patches(const std::string& path)
{
    std::vector<Patch> out;
    std::ifstream in(path);
    std::string line;
    while (std::getline(in, line)) {
        if (!line.empty() && line.back() == '\r') line.pop_back();
        if (line.empty() || line[0] == '#') {
            if (!out.empty() && line.empty() && !out.back().lines.empty()) out.back().lines.push_back("");
            continue;
        }
        if (line[0] == '=') {
            std::istringstream s(line.substr(1));
            std::string a, setting, name, value;
            s >> a >> setting >> name >> value;
            Patch p;
            p.address = uint32_t(std::stoul(a, nullptr, 16));
            for (char ch : setting) p.setting += ch == '-' ? '_' : ch;
            p.value_name = name;
            p.new_value = uint32_t(std::stoul(value, nullptr, 0));
            std::getline(s, p.note);
            p.note = note_of("x " + p.note, 1);
            out.push_back(std::move(p));
            continue;
        }
        if (line[0] == '@') {
            std::istringstream s(line.substr(1));
            std::string a, setting;
            s >> a >> setting;
            Patch p;
            p.address = uint32_t(std::stoul(a, nullptr, 16));
            for (char ch : setting) p.setting += ch == '-' ? '_' : ch;
            std::getline(s, p.note);
            p.note = note_of("x " + p.note, 1);
            out.push_back(std::move(p));
            continue;
        }
        if (out.empty() || (line[0] != ' ' && line[0] != '\t'))
            throw std::runtime_error(path + ": C outside a patch: " + line);
        const size_t first = line.find_first_not_of(" \t");
        out.back().lines.push_back(first == std::string::npos ? "" : line.substr(std::min<size_t>(first, 4)));
    }
    for (Patch& p : out) {
        while (!p.lines.empty() && p.lines.back().empty()) p.lines.pop_back();
        if (p.is_value()) {
            if (!p.lines.empty()) throw std::runtime_error(path + ": the value at $" + hex6(p.address) + " has C");
            continue;
        }
        if (p.lines.empty()) throw std::runtime_error(path + ": the patch at $" + hex6(p.address) + " has no C");
        // (its cycles: the CYCLES(n) it adds; and whether it leaves the function)
        for (const std::string& l : p.lines)
            for (size_t q = l.find("CYCLES("); q != std::string::npos; q = l.find("CYCLES(", q + 1))
                if (q == 0 || !(std::isalnum((unsigned char)l[q - 1]) || l[q - 1] == '_'))
                    p.cycles += std::stoi(l.substr(q + 7));
        for (const std::string& l : p.lines)
            for (size_t q = l.find("STEP("); q != std::string::npos; q = l.find("STEP(", q + 1))
                p.steps.push_back(uint32_t(std::stoul(l.substr(q + 5), nullptr, 16)));
        std::string last = p.lines.back();
        last = last.substr(last.find_first_not_of(" \t"));
        p.leaves = last.rfind("return ", 0) == 0 || last.rfind("JUMP(", 0) == 0;
        for (const std::string& l : p.lines)
            p.calls = p.calls || l.find("CALL(") != std::string::npos;
    }
    return out;
}

