// Musashi's disassembler reads the instructions from the ROM.
extern "C" unsigned int m68k_read_disassembler_8(unsigned int a)
{
    return a < g_rom_bytes->size() ? (*g_rom_bytes)[a] : 0xFF;
}
extern "C" unsigned int m68k_read_disassembler_16(unsigned int a)
{
    return m68k_read_disassembler_8(a) << 8 | m68k_read_disassembler_8(a + 1);
}
extern "C" unsigned int m68k_read_disassembler_32(unsigned int a)
{
    return m68k_read_disassembler_16(a) << 16 | m68k_read_disassembler_16(a + 2);
}
extern "C" unsigned int m68k_disassemble(char* str_buff, unsigned int pc, unsigned int cpu_type);
extern "C" void coi_cycles_68000(uint8_t* out);
unsigned char m68ki_cycles[1][0x10000];             // (native_rt.h's name: the cycle table)

int main(int argc, char** argv)
{
    const bool readable = argc > 1 && std::string(argv[1]) == "--readable";
    if (readable) {
        argv++;
        argc--;
    }
    const int fixed = readable ? 5 : 4;             // (with RESUME.c)
    if (argc != fixed && argc != fixed + 1) {
        std::fprintf(stderr, "usage: coi_recomp [--readable] ROM CONFIG OUT.c [RESUME.c] [SUBROUTINES]\n");
        return 1;
    }
    coi_cycles_68000(m68ki_cycles[0]);              // the cycle table, and decoding against it
    use_opcode_table(m68ki_cycles[0]);
    std::ifstream f(argv[1], std::ios::binary);
    if (!f) {
        std::fprintf(stderr, "coi_recomp: can't read %s\n", argv[1]);
        return 1;
    }
    std::vector<uint8_t> bytes((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
    // An image family (docs/decompile.md: coi --save-rom-family DIR, ROM = DIR/base.bin): the
    // settings' images beside it, named in DIR/family.txt in bit order. What a setting adds
    // outside the base program's code (its own routines, its data) joins the base image, so every
    // function exists in one program; what it changes in the base's code becomes its variants.
    struct Member {
        std::string name;
        std::vector<uint8_t> bytes;
    };
    std::vector<Member> family;
    const uint64_t base_hash = coi_native_hash(bytes.data(), uint32_t(bytes.size()));
    const std::vector<uint8_t> base_bytes = bytes;      // (the base image as it is, before the mix)
    if (readable) {
        const std::string rom_path = argv[1];
        const std::string dir = rom_path.substr(0, rom_path.find_last_of("/\\") + 1);
        std::ifstream list_in(dir + "family.txt");
        std::string name;
        while (list_in >> name) {
            std::ifstream in(dir + name + ".bin", std::ios::binary);
            if (!in) {
                std::fprintf(stderr, "coi_recomp: can't read %s%s.bin\n", dir.c_str(), name.c_str());
                return 1;
            }
            family.push_back({name, std::vector<uint8_t>((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>())});
        }
    }
    g_rom_bytes = &bytes;
    const Rom rom{bytes};
    std::string code, resume_code;
    try {
        Config config;
        load_config(argv[2], config);
        std::vector<uint32_t> list;
        if (argc == fixed + 1) {
            list = load_function_list(argv[fixed]);
            std::string sites = argv[fixed];
            const size_t slash = sites.find_last_of("/\\");
            const std::string dir = slash == std::string::npos ? "" : sites.substr(0, slash + 1);
            // (the tracer's build/trace/sites.txt, or its copy beside config/recomp_functions.txt)
            const std::string copy_name = "recomp_functions.txt";
            const bool config_copy = sites.size() >= copy_name.size()
                && sites.compare(sites.size() - copy_name.size(), copy_name.size(), copy_name) == 0;
            sites = dir + (config_copy ? "recomp_sites.txt" : "sites.txt");
            if (std::ifstream(sites))
                load_config(sites, config);
        }
        if (!family.empty()) {
            // (the base program's instructions: what a setting writes anywhere else is an addition)
            Program base(rom, config);
            base.add_all(list, nullptr);
            std::vector<bool> code(bytes.size());
            for (const auto& [entry, fn] : base.functions())
                for (const auto& [a, in] : fn.insns) {
                    // (the tracer's list holds the settings' routines too: where the base image has
                    // none, its $FF filler decodes as line-F words, which are no code)
                    if (in.op == Op::LineF || in.op == Op::Illegal) continue;
                    for (int n = 0; n < in.length && a + n < code.size(); n++)
                        code[a + n] = true;
                }
            const std::vector<uint8_t> original = bytes;     // (each setting against the base, not the mix)
            for (const Member& m : family)
                for (size_t a = 0; a < bytes.size() && a < m.bytes.size(); a++)
                    if (!code[a] && m.bytes[a] != original[a] && !(a >= 0x18E && a < 0x190))   // (not the checksum)
                        bytes[a] = m.bytes[a];
        }
        Program program(rom, config);
        std::vector<std::pair<uint32_t, std::string>> skipped;
        program.add_all(list, &skipped);
        for (const auto& [a, why] : skipped)
            std::printf("coi_recomp: skipped $%06X: %s\n", a, why.c_str());
        if (argc == fixed + 1)
            std::printf("coi_recomp: %zu functions translated, %zu from the list skipped\n", program.entries().size(),
                        skipped.size());
        if (readable) {
            std::map<uint32_t, std::string> labels = load_labels(argv[2]);
            std::map<uint32_t, std::pair<std::string, std::string>> kinds;     // object IDs (config/object_ids.txt)
            {
                const std::string dir = std::string(argv[2]).substr(0, std::string(argv[2]).find_last_of("/\\") + 1);
                std::ifstream in(dir + "object_ids.txt");
                std::string line;
                while (std::getline(in, line)) {
                    std::istringstream s(line);
                    std::string a, name;
                    if (!(s >> a >> name) || a[0] == '#' || !std::isxdigit((unsigned char)a[0]))
                        continue;
                    kinds[uint32_t(std::stoul(a, nullptr, 16))] = {name, note_of(line, 2)};
                }
            }
            std::map<uint32_t, uint32_t> owner;
            object_names(program, label_addresses(argv[2]), labels, g_label_notes, kinds, owner);
            ReadableNames names;
            // RAM variables and hardware registers (config/ram.txt, hardware.txt, beside CONFIG).
            const std::string config_dir = std::string(argv[2]).substr(0, std::string(argv[2]).find_last_of("/\\") + 1);
            for (const char* file : {"ram.txt", "hardware.txt"}) {
                std::ifstream in(config_dir + file);
                std::string line;
                while (std::getline(in, line)) {
                    std::istringstream s(line);
                    std::string a, name;
                    if (!(s >> a >> name) || a[0] == '#' || !std::isxdigit((unsigned char)a[0]))
                        continue;
                    bool ok = !std::isdigit((unsigned char)name[0]);
                    for (char ch : name) ok = ok && (std::isalnum((unsigned char)ch) || ch == '_');
                    if (ok) {
                        names.addresses[uint32_t(std::stoul(a, nullptr, 16)) & 0xFFFFFF] = name;
                        const std::string note = note_of(line, 2);
                        if (!note.empty()) names.address_notes[uint32_t(std::stoul(a, nullptr, 16)) & 0xFFFFFF] = note;
                    }
                }
            }
            names.function_notes = g_label_notes;
            names.function_kind = owner;
            {
                // Fields per kind of object (config/object_fields.txt): <ID> <offset> <name> [comment].
                const std::string dir = std::string(argv[2]).substr(0, std::string(argv[2]).find_last_of("/\\") + 1);
                std::ifstream in(dir + "object_fields.txt");
                std::string line;
                while (std::getline(in, line)) {
                    std::istringstream s(line);
                    std::string id, off, name;
                    if (!(s >> id >> off >> name) || id[0] == '#' || !std::isxdigit((unsigned char)id[0]))
                        continue;
                    names.kind_fields[uint32_t(std::stoul(id, nullptr, 16))][uint32_t(std::stoul(off, nullptr, 16))] = name;
                    const std::string note = note_of(line, 3);
                    if (!note.empty()) names.kind_field_notes[name] = note;
                }
            }
            // ROM data (labels.txt's data labels), named like RAM where the code loads its address.
            {
                const std::string dir = std::string(argv[2]).substr(0, std::string(argv[2]).find_last_of("/\\") + 1);
                for (const char* file : {"labels.txt", "port_labels.txt"}) {
                    std::ifstream in(dir + file);
                    std::string line;
                    while (std::getline(in, line)) {
                        std::istringstream s(line);
                        std::string a, name, kind;
                        if (!(s >> a >> name >> kind) || a[0] == '#' || kind != "data" || !std::isxdigit((unsigned char)a[0]))
                            continue;
                        const uint32_t at = uint32_t(std::stoul(a, nullptr, 16)) & 0xFFFFFF;
                        if (!names.addresses.count(at)) {
                            names.addresses[at] = name;
                            const std::string note = note_of(line, 0);
                            if (!note.empty()) names.address_notes[at] = note;
                        }
                    }
                }
            }
            {
                std::ifstream in(config_dir + "objects.txt");
                std::string line;
                while (std::getline(in, line)) {
                    std::istringstream s(line);
                    std::string a, name;
                    if (!(s >> a >> name) || a[0] == '#' || !std::isxdigit((unsigned char)a[0]))
                        continue;
                    names.fields[uint32_t(std::stoul(a, nullptr, 16))] = name;
                    const std::string note = note_of(line, 2);
                    if (!note.empty()) names.field_notes[uint32_t(std::stoul(a, nullptr, 16))] = note;
                }
            }
            names.function = [&labels](uint32_t a) {
                auto it = labels.find(a);
                return it != labels.end() ? it->second : "sub_" + hex6(a);
            };
            names.disassemble = [](uint32_t a) {
                char buf[128];
                m68k_disassemble(buf, a, 1);    // (M68K_CPU_TYPE_68000)
                for (char* p = buf; *p; p++)
                    if (*p == '*' && p[1] == '/') p[1] = ' ';
                return std::string(buf);
            };
            // (The readable functions are static: a game's names can be anything, a Windows API
            // function's included. The resumable copy calls them through the lookup.)
            // Each setting's program (its image, the same list), and the functions whose code it
            // changes: their variants.
            std::vector<std::unique_ptr<Rom>> member_roms;
            std::vector<std::unique_ptr<Program>> member_programs;
            std::vector<ReadableVariant> variants;
            std::map<uint32_t, uint32_t> extra_resume;
            std::set<uint32_t> added;       // (a setting's own routines, joined to the base)
            for (const auto& [entry, f2] : program.functions()) added.insert(entry);
            for (size_t k = 0; k < family.size(); k++) {
                member_roms.push_back(std::make_unique<Rom>(Rom{family[k].bytes}));
                member_programs.push_back(std::make_unique<Program>(*member_roms.back(), config));
                member_programs.back()->add_all(list, nullptr);
                // (a setting's own routines, which the base image now holds as well: in the base
                // program too, where their code there is the same)
                for (const auto& [entry, f2] : member_programs.back()->functions()) {
                    if (program.functions().count(entry)) continue;
                    bool same = true;
                    for (const auto& [a, in] : f2.insns)
                        for (int n = 0; same && n < in.length; n++)
                            same = a + n < bytes.size() && family[k].bytes[a + n] == bytes[a + n];
                    if (same) program.add(entry);
                }
            }
            {
                std::set<uint32_t> base_only = std::move(added);
                added.clear();
                for (const auto& [entry, f2] : program.functions())
                    if (!base_only.count(entry)) added.insert(entry);
            }
            // The hand-written patches (config/patches.txt), for an image family only: each checked
            // against its setting's image (what it replaces is one instruction of the base, whose
            // bytes are the only ones in its range the setting changes, and its CYCLES are what the
            // setting's code there takes), and those bytes are then no variant's.
            std::map<uint32_t, std::vector<std::pair<uint32_t, uint32_t>>> covered;     // bit -> [from, to)
            if (!family.empty()) {
                for (const Member& m : family) {
                    std::string c_name;
                    for (char ch : m.name) c_name += ch == '-' ? '_' : ch;
                    names.settings.push_back(c_name);
                }
                for (Patch& p : load_patches(config_dir + "patches.txt")) {
                    const auto bit = std::find(names.settings.begin(), names.settings.end(), p.setting);
                    if (bit == names.settings.end())
                        throw std::runtime_error("patches.txt: $" + hex6(p.address) + ": no setting " + p.setting);
                    p.bit = uint32_t(bit - names.settings.begin());
                    const Insn base_in = program.insn_at(p.address);
                    const Program& pk = *member_programs[p.bit];
                    const uint32_t from = p.address;
                    uint32_t to = from + uint32_t(base_in.length);
                    if (!p.is_value()) {
                        // (the base's instructions it replaces: up to where the setting's start one at
                        // the same place, or past where the setting's code leaves)
                        uint32_t sa = from;
                        bool gone = false;
                        for (;;) {
                            while (sa < to && !gone) {
                                const Insn si = pk.insn_at(sa);
                                sa += uint32_t(si.length);
                                gone = ends_block(si);
                            }
                            if (sa == to || (gone && sa <= to)) break;
                            to += uint32_t(program.insn_at(to).length);
                        }
                    }
                    p.original.assign(base_bytes.begin() + from, base_bytes.begin() + to);
                    const std::vector<uint8_t>& mb = family[p.bit].bytes;
                    bool differs = false;
                    for (uint32_t a = from; a < to; a++) differs |= mb[a] != base_bytes[a];
                    if (!differs)
                        throw std::runtime_error("patches.txt: " + p.setting + " doesn't change $" + hex6(from));
                    // (its CALLs: to functions by their names; the resumable copy calls through the lookup)
                    p.rs_lines = p.lines;
                    for (std::string& l : p.rs_lines)
                        for (size_t q = l.find("CALL("); q != std::string::npos; q = l.find("CALL(", q + 1)) {
                            const size_t e = l.find(',', q);
                            const std::string name = l.substr(q + 5, e == std::string::npos ? 0 : e - q - 5);
                            uint32_t target = 0xFFFFFFFF;
                            for (const auto& [entry, f2] : program.functions())
                                if (names.function(entry) == name) target = entry;
                            if (target == 0xFFFFFFFF)
                                throw std::runtime_error("patches.txt: $" + hex6(from) + " calls " + name + ", which isn't a function");
                            l = l.substr(0, q + 5) + "coi_native_lookup(" + hexv(target) + ")" + l.substr(e);
                        }
                    if (p.is_value()) {
                        // The same instruction with one constant changed: the base's and the
                        // setting's lowered the same but for that constant (old -> new).
                        const Insn set_in = pk.insn_at(from);
                        const IrBlock lb = lower(program, base_in), ls = lower(pk, set_in);
                        bool same = set_in.length == base_in.length && lb.code.size() == ls.code.size(), found = false;
                        for (size_t q = 0; same && q < lb.code.size(); q++) {
                            const IrInst &x = lb.code[q], &y = ls.code[q];
                            same = x.op == y.op && x.size == y.size && x.dst == y.dst && x.k2 == y.k2
                                   && (x.k == y.k || (x.op == Ir::Cycles && m68ki_cycles[0][x.k & 0xFFFF] == m68ki_cycles[0][y.k & 0xFFFF]));
                            for (int w = 0; same && w < 2; w++) {
                                const Val &u = w ? x.b : x.a, &v = w ? y.b : y.a;
                                same = u.kind == v.kind;
                                if (same && u.n != v.n) {
                                    same = u.kind == Val::Imm && v.n == p.new_value && (!found || u.n == p.old_value);
                                    p.old_value = u.n;
                                    found = true;
                                    p.places.push_back({q, w});
                                }
                            }
                        }
                        if (!same || !found)
                            throw std::runtime_error("patches.txt: $" + hex6(from) + ": " + p.setting + "'s instruction isn't the same "
                                                     "with " + p.value_name + " = " + std::to_string(p.new_value));
                        for (const auto& [a2, q] : names.patches)
                            if (q.value_name == p.value_name
                                && (q.old_value != p.old_value || q.new_value != p.new_value || q.setting != p.setting))
                                throw std::runtime_error("patches.txt: " + p.value_name + " differs at $" + hex6(from));
                        covered[p.bit].push_back({from, to});
                        names.patches[p.address] = p;
                        continue;
                    }
                    int cycles = 0;
                    std::vector<uint32_t> starts;
                    for (uint32_t a = from; a < to;) {
                        if (a != from) starts.push_back(a);
                        const Insn in = pk.insn_at(a);
                        for (const IrInst& i : lower(pk, in).code)
                            if (i.op == Ir::Cycles) cycles += m68ki_cycles[0][i.k & 0xFFFF];
                            else if (i.op == Ir::AddCycles && i.a.kind == Val::Imm) cycles += int32_t(i.a.n);
                        a += uint32_t(in.length);
                        if (ends_block(in)) break;
                    }
                    if (cycles != p.cycles)
                        throw std::runtime_error("patches.txt: $" + hex6(from) + " adds " + std::to_string(p.cycles)
                                                 + " cycles; " + p.setting + "'s code there takes " + std::to_string(cycles));
                    if (starts != p.steps)
                        throw std::runtime_error("patches.txt: $" + hex6(from) + ": its STEPs aren't where " + p.setting
                                                 + "'s instructions start");
                    covered[p.bit].push_back({from, to});
                    names.patches[p.address] = p;
                }
            }
            for (size_t k = 0; k < family.size(); k++) {
                Program& pk = *member_programs[k];
                // (every function the base program has, so each can be compared: some are only
                // reached from callers a setting changes)
                for (const auto& [entry, fb] : program.functions())
                    if (!pk.functions().count(entry)) {
                        try {
                            pk.add(entry);
                        } catch (const std::exception&) {
                        }
                    }
                ReadableVariant v;
                v.program = &pk;
                v.bit = uint32_t(k);
                v.suffix = "__" + family[k].name;
                for (char& ch : v.suffix)
                    if (ch == '-') ch = '_';
                const std::vector<uint8_t>& mb = family[k].bytes;
                // A function is this setting's if a byte of its code, in either image, is one the
                // setting changes (against the base image itself: what other settings add to the
                // mix isn't this one's).
                // (a byte a hand-written patch covers is no variant's)
                auto patched = [&](uint32_t a) {
                    for (const auto& [from, to] : covered[uint32_t(k)])
                        if (a >= from && a < to) return true;
                    return false;
                };
                auto changes = [&](const Function& fn) {
                    for (const auto& [a, in] : fn.insns)
                        for (int n = 0; n < in.length; n++)
                            if (a + n < mb.size() && a + n < base_bytes.size() && mb[a + n] != base_bytes[a + n]
                                && !(a + n >= 0x18E && a + n < 0x190) && !patched(a + n))
                                return true;
                    return false;
                };
                for (const auto& [entry, fb] : program.functions()) {
                    // (a setting's own routine is the same code in the base program, which has it
                    // from that setting's image: only the setting's code reaches it, so it needs
                    // no variant)
                    if (added.count(entry)) continue;
                    auto it = pk.functions().find(entry);
                    const bool mine = changes(fb) || (it != pk.functions().end() && changes(it->second));
                    if (!mine) continue;
                    if (it == pk.functions().end())
                        throw std::runtime_error("$" + hex6(entry) + " can't be translated in " + family[k].name + "'s image");
                    v.entries.insert(entry);
                    for (const auto& [a, in] : it->second.insns)
                        if (!fb.insns.count(a)) extra_resume.emplace(a, entry);
                }
                for (const auto& [entry, f2] : pk.functions())
                    if (!program.functions().count(entry))
                        std::fprintf(stderr, "coi_recomp: $%06X is only in %s's image (left out)\n", entry, family[k].name.c_str());
                v.disassemble = [&mb](uint32_t a) {
                    const std::vector<uint8_t>* keep = g_rom_bytes;
                    g_rom_bytes = &mb;
                    char buf[128];
                    m68k_disassemble(buf, a, 1);
                    g_rom_bytes = keep;
                    for (char* p = buf; *p; p++)
                        if (*p == '*' && p[1] == '/') p[1] = ' ';
                    return std::string(buf);
                };
                std::printf("coi_recomp: %s changes %zu functions\n", family[k].name.c_str(), v.entries.size());
                variants.push_back(std::move(v));
            }
            // (a patch's STEPs: resumed in the first function that holds the patch)
            for (const auto& [a, p] : names.patches)
                for (uint32_t s : p.steps)
                    for (const auto& [entry, fb] : program.functions())
                        if (fb.insns.count(a)) {
                            bool variant = false;
                            for (const ReadableVariant& v : variants)
                                variant |= v.bit == p.bit && v.entries.count(entry);
                            if (variant)
                                throw std::runtime_error("patches.txt: $" + hex6(a) + "'s STEPs: its first function is a variant");
                            extra_resume.emplace(s, entry);
                            break;
                        }
            CEmitter c(program);
            c.resumable([](uint32_t a) { return "coi_native_lookup(" + hexv(a) + ")"; });
            for (const ReadableVariant& v : variants)
                for (uint32_t entry : v.entries)
                    c.dispatch[entry].push_back({v.bit, v.suffix});
            std::string patch_head;
            if (!names.patches.empty()) {
                // (the patches' C is in readable_rt.h's names, the settings' bits and the fixed
                // addresses it names: those defined here too)
                patch_head = "#include \"readable_rt.h\"\n\n";
                for (size_t k = 0; k < names.settings.size(); k++)
                    patch_head += "#define SETTING_" + names.settings[k] + " " + hexv(1u << k) + "\n";
                std::set<std::string> values;
                for (const auto& [a, p] : names.patches)
                    if (p.is_value() && values.insert(p.value_name).second)
                        patch_head += "#define " + p.value_name + " (SETTING(" + p.setting + ") ? " + hexv(p.new_value) + " : "
                                      + hexv(p.old_value) + ")\n";
                std::set<std::string> used;
                for (const auto& [a, p] : names.patches)
                    for (const std::string& l : p.lines)
                        for (const auto& [at, name] : names.addresses)
                            for (size_t q = l.find(name); q != std::string::npos; q = l.find(name, q + 1)) {
                                auto word = [&](size_t i) { return i < l.size() && (std::isalnum((unsigned char)l[i]) || l[i] == '_'); };
                                if ((q == 0 || !word(q - 1)) && !word(q + name.size()) && used.insert(name).second)
                                    patch_head += "#define " + name + " 0x" + hex6(at) + "u\n";
                            }
                patch_head += "\n";
            }
            c.patches = &names.patches;
            c.patch_head = patch_head;
            resume_code = c.emit_resumable();
            // The resume table's owners (as run_and_tables picks them: the first function holding
            // the address), for the variants' redirects.
            std::map<uint32_t, uint32_t> owner_of;
            for (const auto& [entry, fb] : program.functions())
                for (const auto& [a, in] : fb.insns)
                    owner_of.emplace(a, entry);
            for (const auto& [a, entry] : extra_resume)
                owner_of.emplace(a, entry);
            for (const ReadableVariant& v : variants) {
                CEmitter cv(*v.program);
                cv.resumable([](uint32_t a) { return "coi_native_lookup(" + hexv(a) + ")"; });
                cv.suffix = v.suffix;
                cv.patches = &names.patches;
                cv.own_bits = 1u << v.bit;
                std::map<uint32_t, uint32_t> holder;        // (in the setting's program)
                for (const auto& [entry, fv] : v.program->functions())
                    for (const auto& [a, in] : fv.insns)
                        holder.emplace(a, entry);
                for (const auto& [a, entry] : owner_of) {
                    if (!v.entries.count(entry) || v.program->functions().at(entry).insns.count(a)) continue;
                    auto h = holder.find(a);
                    if (h == holder.end()) continue;        // (not an instruction with the setting on)
                    cv.redirect[entry].push_back({a, "coi_rs_" + hex6(h->second) + (v.entries.count(h->second) ? v.suffix : "")});
                }
                resume_code += cv.emit_resumable_part(v.entries);
            }
            CEmitter tables(program);
            tables.resumable(names.function);
            tables.extra_resume = extra_resume;
            if (!family.empty()) {
                tables.family.push_back(base_hash);
                for (const Member& m : family)
                    tables.family.push_back(coi_native_hash(m.bytes.data(), uint32_t(m.bytes.size())));
            }
            code = emit_readable(program, names, variants) + tables.run_and_tables(true);
        } else {
            code = CEmitter(program).emit();
        }
    } catch (const std::exception& ex) {
        std::fprintf(stderr, "coi_recomp: %s\n", ex.what());
        return 1;
    }
    std::ofstream out(argv[3], std::ios::binary);
    out << code;
    if (readable) {
        std::ofstream r(argv[4], std::ios::binary);
        r << resume_code;
        if (!r)
            return 1;
    }
    return out ? 0 : 1;
}
