// coi_recomp [--readable] ROM CONFIG OUT.c [RESUME.c] [SUBROUTINES]: translates the 68000 functions CONFIG lists from the
// player's ROM into C (the development back end of the recompiler, for checking it against the
// interpreter). The output is game code, so it is written into the build folder only, never
// the repository. CONFIG is config/recomp.txt (see program.h).
//
// SUBROUTINES (optional, the tracer's build/trace/subroutines.txt): also translate every
// function listed there that it can, skipping (with a note) the ones it can't yet; calls to a
// skipped function stop the translated code (cpu->fail). The tracer's sites.txt beside it, if
// there, adds the jump tables it found as jump/call lines (CONFIG's own lines win).
//
// Each function becomes `uint32_t coi_fn_XXXXXX(CoiCpu*, uint32_t at)`: entered with the return
// address on the stack, as a jsr leaves it, and returning the address its rts goes to. It can
// also start at any of its instructions (`at`), so code stopped partway can carry on natively:
// every return address is on the 68000's own stack, so nothing else needs restoring. Inside it
// every instruction is a labelled C block (its IR, lower.cpp) and branches are gotos; calls are
// C calls that check the callee returned where the 68000 would have. A jmp leaves the function
// (the code it goes to is a function of its own, run by coi_native_run's loop), so shared code
// isn't copied into every function that jumps to it.
//
// --readable (docs/decompile.md): OUT.c gets each function as readable C (readable.cpp), and
// RESUME.c the code above as the resumable copy (coi_rs_XXXXXX), which the readable functions
// hand a call to when a scanline's cycles may run out partway. Names come from labels.txt beside
// CONFIG, and each instruction's assembly (Musashi's disassembler) is a comment.

