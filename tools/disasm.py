"""Generate Macroassembler AS source for the regions in config/regions.txt.

Uses the code map from tools/trace.py. For each region it writes src/<name>.asm:
traced instructions with labels and explicit sizes, jump tables as label
expressions, and everything else as dc.b data. It also writes:
  src/symbols.asm  equates for labels outside the disassembled regions
  src/layout.asm   the ROM layout: regions interleaved with binclude ranges

Usage: python tools/disasm.py
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import trace  # noqa: E402  (tools/trace.py, not the standard library module)
import z80dis  # noqa: E402

ROOT = trace.ROOT
SRC = ROOT / "src"
REGIONS = ROOT / "config" / "regions.txt"
RAM = ROOT / "config" / "ram.txt"
Z80_NAMES = ROOT / "config" / "z80.txt"
HARDWARE = ROOT / "config" / "hardware.txt"

BRANCH = re.compile(r"^(b(ra|sr|hi|ls|cc|cs|ne|eq|vc|vs|pl|mi|ge|lt|gt|le))\.([bw])$")
DBCC = re.compile(r"^db\w+$")
# Bit operations take their size from the destination; AS wants no suffix.
BITOPS = {"btst", "bchg", "bclr", "bset"}
# Mnemonics whose size suffix AS does not accept or does not need.
NO_SUFFIX = {"lea", "pea", "exg", "jmp", "jsr", "moveq", "swap", "unlk", "link", "nop",
             "rts", "rte", "rtr", "stop", "trap", "reset", "illegal", "tas"}
NUM = r"\$[0-9a-f]+"
ZERO_DISP = re.compile(r"(^|[ ,])\$0\(a\d\)")


def load_regions():
    """68000 regions as (start, end, name); Z80 regions as (start, end, name, load address)."""
    regions, z80_regions = [], []
    for line in REGIONS.read_text().splitlines():
        words = line.split("#", 1)[0].split()
        if not words:
            continue
        start, end, name = int(words[0], 16), int(words[1], 16), words[2]
        if len(words) > 3 and words[3].startswith("z80@"):
            z80_regions.append((start, end, name, int(words[3][4:], 16)))
        else:
            regions.append((start, end, name))
    return sorted(regions), sorted(z80_regions)


def z80_region(rom, start, end, name, load, names, code_names):
    """Trace and render one Z80 block; returns (source lines, tracer)."""
    mem = bytearray(0x10000)
    mem[load:load + end - start] = rom[start:end]
    tracer = z80dis.Z80Tracer(mem, load, load + end - start, [0x0000, 0x0038]).run()
    gen = z80dis.Z80Generator(tracer, mem, load, names=code_names, data_names=names)
    body = gen.lines()
    # AS checks Z80 addresses against the 64 KB Z80 space even inside a phase
    # block, so the driver is a standalone program: tools/build.py assembles it
    # to build/<name>.bin first, and src/layout.asm bincludes that.
    out = ["; " + "-" * 75,
           "; %s: ROM $%06X-$%06X, Z80 code loaded at $%04X (generated by tools/disasm.py)"
           % (name, start, end, load),
           "; Assembled on its own to build/%s.bin, which the main build includes." % name,
           "; " + "-" * 75, "",
           "\tcpu\tz80",
           "\trelaxed\ton",
           '\tinclude\t"src/z80names.asm"',
           "",
           "\torg\t$%04X" % load]
    out += body
    out.append("")
    if gen.used_external:
        out.append("; Z80 addresses outside this block")
        out += ["%s\tequ\t$%04X" % (gen.names[a], a) for a in sorted(gen.used_external)]
    return out, tracer


def load_names(path, base=0):
    """Read '<hex address> <name> [comment]' lines; addresses are ORed with base."""
    names = {}
    for line in path.read_text().splitlines():
        words = line.split("#", 1)[0].split(None, 2)
        if words:
            names[base | int(words[0], 16)] = (words[1], words[2] if len(words) > 2 else "")
    return names


def load_ram():
    return load_names(RAM, 0xFF000000)


def hexnum(value):
    return "$%X" % value


def upper_hex(text):
    return re.sub(r"\$[0-9a-f]+", lambda m: m.group(0).upper(), text)


class Generator:
    def __init__(self, tracer, regions, ram=None, hardware=None):
        self.t = tracer
        self.regions = regions
        self.ram = ram or {}   # sign-extended RAM address -> (name, comment)
        self.hardware = hardware or {}   # absolute hardware address -> (name, comment)
        self.names = {}        # address -> label name
        self.defined = set()   # labels emitted inside regions
        self.used = set()      # labels referenced from emitted code

        for address, (name, _) in tracer.labels.items():
            self.names[address] = name
        for address in tracer.subroutines:
            self.names.setdefault(address, "sub_%06X" % address)
        for table, (_, targets) in tracer.jump_tables.items():
            self.names.setdefault(table, "tbl_%06X" % table)
            for target in targets:
                self.names.setdefault(target, "loc_%06X" % target)
        for insn in tracer.insns.values():
            for target in self.code_refs(insn):
                if self.inside_instruction(target):
                    continue          # referenced as <instruction label>+offset instead
                is_code = target in tracer.insns or target in tracer.jump_tables
                self.names.setdefault(target, ("loc_%06X" if is_code else "dat_%06X") % target)

    def in_regions(self, address):
        return any(start <= address < end for start, end, _ in self.regions)

    @staticmethod
    def code_refs(insn):
        """ROM addresses an instruction refers to through branches or pc-relative operands."""
        refs = []
        mnemonic = insn.mnemonic.split(".")[0]
        if BRANCH.match(insn.mnemonic) or DBCC.match(mnemonic):
            refs.append(int(insn.op_str.split(", ")[-1][1:], 16))
        for m in re.finditer(r"(%s)\(pc" % NUM, insn.op_str):
            refs.append(int(m.group(1)[1:], 16))
        if mnemonic in ("jmp", "jsr"):
            m = re.match(r"^(%s)\.l$" % NUM, insn.op_str)
            if m:
                refs.append(int(m.group(1)[1:], 16))
        return [r for r in refs if 0x200 <= r < trace.ROM_END]

    def inside_instruction(self, address):
        owner = self.t.owner.get(address)
        return owner is not None and owner != address

    def label(self, address):
        # Some tables are addressed through a base that falls inside an
        # instruction (e.g. movea.l base(pc,d1.w),a0 where d1 is never small).
        # Such an address has no label of its own; refer to it from the
        # instruction that contains it.
        if self.inside_instruction(address):
            owner = self.t.owner[address]
            return "%s+%d" % (self.label(owner), address - owner)
        name = self.names.get(address)
        if name is None:
            name = self.names[address] = "loc_%06X" % address
        self.used.add(address)
        return name

    def operand(self, text):
        """Convert one Capstone operand to AS syntax."""
        m = re.match(r"^(%s)\.([wl])$" % NUM, text)
        if m:
            value = int(m.group(1)[1:], 16)
            if m.group(2) == "w" and value >= 0x8000:
                value |= 0xFFFF0000          # absolute short addresses are sign-extended
            # RAM is $FF0000-$FFFFFF; config/ram.txt keys use the sign-extended form
            ram = self.ram.get(0xFF000000 | value) if value & 0xFFFFFF >= 0xFF0000 else None
            if ram:
                return "(%s).%s" % (ram[0], m.group(2))
            if m.group(2) == "l" and value in self.hardware:
                return "(%s).l" % self.hardware[value][0]
            if m.group(2) == "l" and 0x200 <= value < trace.ROM_END and value in self.names:
                return "(%s).l" % self.label(value)
            return "(%s).%s" % (hexnum(value), m.group(2))
        m = re.match(r"^(%s)\(pc(, .*)?\)$" % NUM, text)
        if m:
            target = int(m.group(1)[1:], 16)
            index = (m.group(2) or "").replace(" ", "")
            return "%s(pc%s)" % (self.label(target), index)
        return upper_hex(text.replace(", ", ","))

    @staticmethod
    def split_operands(op_str):
        """Split on commas outside parentheses."""
        parts, depth, current = [], 0, ""
        for ch in op_str:
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            if ch == "," and depth == 0:
                parts.append(current.strip())
                current = ""
            else:
                current += ch
        if current.strip():
            parts.append(current.strip())
        return parts

    @staticmethod
    def needs_raw(insn):
        """True when AS cannot reproduce the original encoding.

        A byte-sized immediate (and the bit number of a static bit operation)
        occupies a full extension word whose high byte the CPU ignores. AS
        always writes it as zero, so a nonzero high byte must be kept as data.

        AS also replaces a zero displacement $0(an) with the shorter (an).
        """
        base, _, size = insn.mnemonic.partition(".")
        if ZERO_DISP.search(insn.op_str):
            return True
        if base in ("addq", "subq", "moveq") or not insn.op_str.startswith("#"):
            return False
        return (size == "b" or base in BITOPS) and insn.size >= 4 and insn.bytes[2] != 0

    def instruction(self, insn):
        mnemonic = insn.mnemonic
        base, _, size = mnemonic.partition(".")
        operands = self.split_operands(insn.op_str)

        if self.needs_raw(insn):
            words = [insn.bytes[i:i + 2].hex().upper() for i in range(0, insn.size, 2)]
            if ZERO_DISP.search(insn.op_str):
                why = "AS would shorten the zero displacement to (an)"
            else:
                why = "nonzero high byte in the immediate word"
            return "dc.w\t%s\t; %s %s (%s)" % (
                ",".join("$" + w for w in words), mnemonic, upper_hex(insn.op_str.replace(", ", ",")), why)

        m = BRANCH.match(mnemonic)
        if m:
            target = int(insn.op_str[1:], 16)
            return "%s.%s\t%s" % (m.group(1), "s" if m.group(3) == "b" else "w", self.label(target))
        if DBCC.match(base):
            target = int(operands[-1][1:], 16)
            return "%s\t%s,%s" % (base, operands[0], self.label(target))

        if base in BITOPS or base in NO_SUFFIX:
            mnemonic = base
        if base == "moveq":
            # moveq sign-extends its byte; write negative values as such so AS doesn't warn
            value = int(operands[0][2:], 16) if operands[0].startswith("#$") else None
            if value is not None and value >= 0x80:
                operands[0] = "#-$%X" % (0x100 - value)
        if base == "move" and not size:
            mnemonic = "move.l" if "usp" in insn.op_str else "move.w"
        converted = [self.operand(o) for o in operands]
        return "%s\t%s" % (mnemonic, ",".join(converted)) if converted else mnemonic

    def table_lines(self, table):
        kind, targets = self.t.jump_tables[table]
        size = 4 if kind == "abs32" else 2
        lines = []
        stale = {index: target for t, index, target in self.t.stale if t == table}
        count = len(targets) + len(stale)
        if kind == "rel8":
            base = self.label(self.t.table_bases[table])
            return ["\tdc.b\t%s-%s" % (self.label(t), base) for t in targets], len(targets)
        it = iter(targets)
        for index in range(count):
            if index in stale:
                lines.append("\tdc.w\t%s\t\t; %d: stale, points into other code" % (hexnum(stale[index]), index))
                continue
            target = next(it)
            if kind == "rel16":
                lines.append("\tdc.w\t%s-%s" % (self.label(target), self.label(table)))
            elif kind == "abs16":
                lines.append("\tdc.w\t%s" % self.label(target))
            elif kind == "abs32":
                lines.append("\tdc.l\t%s" % self.label(target))
            else:
                return None, 0
        return lines, count * size

    def region(self, start, end, name):
        out = ["; " + "-" * 75,
               "; %s: $%06X-$%06X (generated by tools/disasm.py)" % (name, start, end),
               "; " + "-" * 75, ""]
        address = start
        data = []

        def flush():
            for i in range(0, len(data), 16):
                out.append("\tdc.b\t" + ",".join("$%02X" % b for b in data[i:i + 16]))
            data.clear()

        while address < end:
            if address in self.names and (address in self.t.insns or address in self.t.jump_tables
                                          or address in self.used or address in self.t.subroutines):
                flush()
                if address in self.t.subroutines:
                    out.append("")
                out.append("%s:" % self.names[address])
                self.defined.add(address)
            if address in self.t.jump_tables and self.t.jump_tables[address][0] != "bra":
                lines, size = self.table_lines(address)
                if lines is not None and address + size <= end:
                    flush()
                    out.extend(lines)
                    address += size
                    continue
            insn = self.t.insns.get(address)
            if insn is not None and address + insn.size <= end:
                flush()
                out.append("\t" + self.instruction(insn))
                address += insn.size
                continue
            data.append(self.t.rom[address])
            address += 1
        flush()
        return out

    def label_positions(self):
        """Labels that must be defined inside regions (to avoid emitting them as equates)."""
        return {a for a in self.names if self.in_regions(a)}


def main():
    if not trace.BASEROM.exists():
        print("build/baserom.bin is missing: run python tools/romcheck.py first.")
        return 1
    rom = trace.BASEROM.read_bytes()
    tracer = trace.Tracer(rom, trace.load_labels(), *trace.load_directives())
    tracer.run()
    regions, z80_regions = load_regions()
    ram = load_ram()
    hardware = load_names(HARDWARE)
    gen = Generator(tracer, regions, ram, hardware)

    # Pass 1 renders every region so the generator learns which labels are used.
    rendered = {name: gen.region(start, end, name) for start, end, name in regions}
    # Labels referenced inside a region but never placed there (e.g. a branch into
    # a data run) would be undefined, so the second pass places them too.
    rendered = {name: gen.region(start, end, name) for start, end, name in regions}

    for name, lines in rendered.items():
        (SRC / (name + ".asm")).write_text("\n".join(lines) + "\n")

    missing = sorted(a for a in gen.used if gen.in_regions(a) and a not in gen.defined)
    if missing:
        print("Labels referenced but not placed: " + " ".join("$%X" % a for a in missing))
        return 1

    externals = sorted(a for a in gen.used if not gen.in_regions(a))
    lines = ["; Equates for labels outside the disassembled regions (generated by tools/disasm.py)", ""]
    lines += ["%s\tequ\t$%06X" % (gen.names[a], a) for a in externals]
    (SRC / "symbols.asm").write_text("\n".join(lines) + "\n")

    lines = ["; RAM variables (generated by tools/disasm.py from config/ram.txt)", ""]
    for address, (name, comment) in sorted(ram.items()):
        lines.append("%s\tequ\t$%08X%s" % (name, address, "\t; " + comment if comment else ""))
    (SRC / "ram.asm").write_text("\n".join(lines) + "\n")

    lines = ["; Hardware addresses (generated by tools/disasm.py from config/hardware.txt)", ""]
    for address, (name, comment) in sorted(hardware.items()):
        lines.append("%s\tequ\t$%06X%s" % (name, address, "\t; " + comment if comment else ""))
    (SRC / "hardware.asm").write_text("\n".join(lines) + "\n")

    z80_all = load_names(Z80_NAMES)
    z80_code = {a: n for a, (n, c) in z80_all.items() if c.split(None, 1)[:1] == ["code"]}
    z80_names = {a: n for a, (n, c) in z80_all.items() if a not in z80_code}
    lines = ["; Z80 address names (generated by tools/disasm.py from config/z80.txt)", ""]
    for address, (name, comment) in sorted(z80_all.items()):
        if address not in z80_code:
            lines.append("%s\tequ\t$%04X%s" % (name, address, "\t; " + comment if comment else ""))
    (SRC / "z80names.asm").write_text("\n".join(lines) + "\n")
    z80_tracers = {}
    for start, end, name, load in z80_regions:
        source, z80_tracers[name] = z80_region(rom, start, end, name, load, z80_names, z80_code)
        (SRC / (name + ".asm")).write_text("\n".join(source) + "\n")

    layout = ["; ROM layout from $000200 (generated by tools/disasm.py from config/regions.txt)", ""]
    position = 0x200
    z80_files = {r[2] for r in z80_regions}
    for start, end, name in sorted(regions + [r[:3] for r in z80_regions]):
        if start > position:
            layout.append('\tbinclude\t"build/baserom.bin",$%06X,$%X' % (position, start - position))
        if name in z80_files:
            layout.append('\tbinclude\t"build/%s.bin"\t; assembled from src/%s.asm' % (name, name))
        else:
            layout.append('\tinclude\t"src/%s.asm"' % name)
        position = end
    if position < trace.ROM_END:
        layout.append('\tbinclude\t"build/baserom.bin",$%06X,$%X' % (position, trace.ROM_END - position))
    (SRC / "layout.asm").write_text("\n".join(layout) + "\n")

    for start, end, name in regions:
        code = sum(i.size for a, i in tracer.insns.items() if start <= a < end)
        print("src/%s.asm: $%06X-$%06X, %d of %d bytes as instructions" % (name, start, end, code, end - start))
    for start, end, name, load in z80_regions:
        t = z80_tracers[name]
        code = sum(i.size for i in t.insns.values())
        raw = sum(1 for i in t.insns.values() if i.raw)
        print("src/%s.asm: $%06X-$%06X (Z80 $%04X), %d of %d bytes as Z80 instructions, %d kept as db"
              % (name, start, end, load, code, end - start, raw))
        for pc, text in t.indirect:
            print("  unresolved Z80 jump at $%04X: %s" % (pc, text))
        for pc, text in t.problems:
            print("  Z80 problem at $%04X: %s" % (pc, text))
    print("src/symbols.asm: %d external labels" % len(externals))
    return 0


if __name__ == "__main__":
    sys.exit(main())
