"""Assemble port/src/boss_rush.asm with asl/p2bin (tools/bin) into port/src/boss_rush_code.h.

The port builds without asl: the header holds the assembled bytes and is committed. Run this
after changing boss_rush.asm.

Usage: python tools/boss_rush_asm.py
"""
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "port" / "src" / "boss_rush.asm"
HEADER = ROOT / "port" / "src" / "boss_rush_code.h"
ORIGIN = 0x0D0000


def tool(name):
    local = ROOT / "tools" / "bin" / (name + ".exe")
    return str(local) if local.exists() else shutil.which(name)


def main():
    asl, p2bin = tool("asl"), tool("p2bin")
    if not asl or not p2bin:
        print("asl/p2bin not found (looked in tools/bin and PATH): see tools/build_asl.py.")
        return 1
    with tempfile.TemporaryDirectory() as work:
        obj, out = Path(work) / "boss_rush.p", Path(work) / "boss_rush.bin"
        if subprocess.call([asl, "-xx", "-q", "-U", "-L", "-i", str(SOURCE.parent), "-olist", str(Path(work) / "boss_rush.lst"),
                            "-o", str(obj), str(SOURCE)]) != 0:
            print((Path(work) / "boss_rush.lst").read_text(errors="replace")[-4000:])
            return 1
        if subprocess.call([p2bin, "-q", "-r", "$%X-$" % ORIGIN, str(obj), str(out)]) != 0:
            return 1
        code = out.read_bytes()
    lines = ["// Generated by tools/boss_rush_asm.py from boss_rush.asm: do not edit.",
             "#pragma once", "", "#include <cstdint>", "",
             "constexpr uint32_t kBossRushOrigin = 0x%06X;" % ORIGIN,
             "constexpr uint8_t kBossRushCode[] = {"]
    for i in range(0, len(code), 16):
        lines.append("    " + ", ".join("0x%02X" % b for b in code[i:i + 16]) + ",")
    lines += ["};", ""]
    HEADER.write_text("\n".join(lines), newline="\n")
    print("%s: %d bytes" % (HEADER.name, len(code)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
