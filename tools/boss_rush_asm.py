"""Assemble port/src/boss_rush.asm with asl/p2bin (tools/bin) into port/src/boss_rush_code.h.

The port builds without asl: the header holds the assembled bytes and is committed. Run this
after changing boss_rush.asm. It also writes config/port_labels.txt, the code's labels and the
RAM it names (from the assembler's symbol table), for the readable C (docs/decompile.md).

Usage: python tools/boss_rush_asm.py
"""
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "port" / "src" / "boss_rush.asm"
HEADER = ROOT / "port" / "src" / "boss_rush_code.h"
LABELS = ROOT / "config" / "port_labels.txt"
ORIGIN = 0x0D0000


def tool(name):
    local = ROOT / "tools" / "bin" / (name + ".exe")
    return str(local) if local.exists() else shutil.which(name)


def main():
    asl, p2bin = tool("asl"), tool("p2bin")
    if not asl or not p2bin:
        print("asl/p2bin not found (looked in tools/bin and PATH): see tools/build_asl.py.")
        return 1
    with tempfile.TemporaryDirectory() as work:
        obj, out = Path(work) / "boss_rush.p", Path(work) / "boss_rush.bin"
        if subprocess.call([asl, "-xx", "-q", "-U", "-L", "-i", str(SOURCE.parent), "-olist", str(Path(work) / "boss_rush.lst"),
                            "-o", str(obj), str(SOURCE)]) != 0:
            print((Path(work) / "boss_rush.lst").read_text(errors="replace")[-4000:])
            return 1
        if subprocess.call([p2bin, "-q", "-r", "$%X-$" % ORIGIN, str(obj), str(out)]) != 0:
            return 1
        code = out.read_bytes()
        listing = (Path(work) / "boss_rush.lst").read_text(errors="replace")
    write_labels(listing)
    lines = ["// Generated by tools/boss_rush_asm.py from boss_rush.asm: do not edit.",
             "#pragma once", "", "#include <cstdint>", "",
             "constexpr uint32_t kBossRushOrigin = 0x%06X;" % ORIGIN,
             "constexpr uint8_t kBossRushCode[] = {"]
    for i in range(0, len(code), 16):
        lines.append("    " + ", ".join("0x%02X" % b for b in code[i:i + 16]) + ",")
    lines += ["};", ""]
    HEADER.write_text("\n".join(lines), newline="\n")
    print("%s: %d bytes" % (HEADER.name, len(code)))
    return 0


def write_labels(listing):
    """The symbol table's code labels (C, from ORIGIN) and RAM names, but not local labels."""
    table = listing[listing.find("Symbol Table"):]
    rows = []
    for name, value, kind in re.findall(r"[ *]([A-Za-z_][A-Za-z0-9_]*) :\s+([0-9A-F]+) ([C-])", table):
        v = int(value, 16) & 0xFFFFFF
        if kind == "C" and v >= ORIGIN:
            rows.append((v, name, "label"))
        elif kind == "-" and v >= 0xFF0000:
            rows.append((v, name, "data"))
    lines = ["# Generated by tools/boss_rush_asm.py from port/src/boss_rush.asm: do not edit. The port's",
             "# own code (Boss Rush, at $%06X) and the RAM it names, as labels.txt has them; where" % ORIGIN,
             "# labels.txt or ram.txt names an address too, theirs is used."]
    # The entry points' jmps at fixed addresses ("jmp (Name).l ; $0D0000"), as NameEntry.
    for target, at in re.findall(r"jmp\s+\((\w+)\)\.l\s*;\s*\$([0-9A-Fa-f]{6})", SOURCE.read_text()):
        rows.append((int(at, 16), target + "Entry", "label"))
    lines += ["%06X %s %s" % row for row in sorted(rows)]
    LABELS.write_text("\n".join(lines) + "\n", newline="\n")
    print("%s: %d labels" % (LABELS.name, len(rows)))


if __name__ == "__main__":
    sys.exit(main())
